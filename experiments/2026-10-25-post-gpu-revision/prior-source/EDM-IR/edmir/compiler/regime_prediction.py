"""Controlled additive/max latency hypothesis for the frozen P4 measurements.

The two branches are statistical proxies, not isolated latency or bandwidth
measurements. A finite partition of coefficient space makes the fixed max model
globally solvable (to the reported numerical tolerances), without random starts.
No compiler admission or modification of the previous model is performed.
"""
from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
import math
import time

from .mechanism_prediction import (
    HOSTS, RIDGE, MAX_ROWS, MechanismModel, geometry, linear_solve,
    matrix_rank, nonnegative_fit,
)

VARIANTS = ("regime_sum", "regime_max")
COMMON = ("fixed", "grouped_partition_depth_64", "dynamic_smem_optins_over_16",
          "SM_spread_deficit", "ordered_epilogue_boundaries", "extra_serial_output_MiB")
NAMES = COMMON + ("latency_depth_64", "throughput_logical_A_MiB")


def regime_basis(shape, family):
    x = geometry(shape, family)
    if x["kind"] != "fused":
        raise ValueError("regime branches only describe the audited fused family")
    depth = x["partition_iterations"]/64
    return NAMES, (1., (x["g"]-1)*depth,
        x["gemm_count"]*int(x["shared_storage_bytes"] >= 48*1024)/16,
        max(1-x["ctas"]/108, 0.), x["q"]-1.,
        x["extra_serial_output_bytes"]/2**20,
        depth, x["logical_A_replay_bytes"]/2**20)


def _quadratic_fit(gram, rhs, deadline):
    """Strictly convex NNQP on one cone; a feasible KKT point is its minimum."""
    d = len(rhs)
    rhs_scale = max(1., max(abs(v) for v in rhs))
    visited = 0
    # Large faces first is deterministic and often finishes early. The bound
    # remains 2**d; no negative feasible coefficient is silently accepted.
    for mask in range((1 << d)-1, -1, -1):
        if time.monotonic() > deadline:
            raise TimeoutError("bounded regime calibration deadline exceeded")
        visited += 1
        active = [j for j in range(d) if mask & (1 << j)]
        solution = linear_solve([[gram[i][j] for j in active] for i in active],
                                [rhs[i] for i in active])
        if solution is None or any(v < -1e-8 for v in solution):
            continue
        z = [0.]*d
        for j, v in zip(active, solution):
            z[j] = max(0., v)
        grad = [math.fsum(gram[i][j]*z[j] for j in range(d))-rhs[i] for i in range(d)]
        relative = max(abs(v) if c > 1e-8 else max(-v, 0.)
                       for v, c in zip(grad, z))/rhs_scale
        if relative <= 1e-9:
            return z, relative, visited
    raise ValueError("no KKT-certified minimum on regime cone")


def max_branch_fit(raw, targets, weights, *, timeout_seconds=10.):
    """Fit common + max(a*L,b*W), where L/W are the last two positive columns.

    Sort r=W/L. For adjacent l,u, the assignment of branches is fixed whenever
    l <= a/b <= u. The coefficient wedge is generated by (l,1) and (u,1),
    with (1,0) for the last infinite endpoint. Nonnegative ray weights turn each
    region into a convex NNQP. Enumerating every interval covers the entire
    nonnegative coefficient domain, including ties and zero branch weights.

    RMS scales use *unmasked training columns*. Ridge is imposed on those same
    original normalized coefficients in every region (R'R after changing
    coordinates), not on arbitrary ray weights. Otherwise interval objectives
    would be incomparable. KKT checks certify regions, not physical causality.
    """
    if (not raw or len(raw) > MAX_ROWS or not 2 <= len(raw[0]) <= 8
            or len(raw) != len(targets) or len(raw) != len(weights)):
        raise ValueError("invalid bounded regime dimensions")
    d, n = len(raw[0]), len(raw)
    if any(len(row) != d for row in raw):
        raise ValueError("ragged regime matrix")
    if any(type(v) not in (int, float) or not math.isfinite(v) or v < 0
           for v in [v for row in raw for v in row]+list(targets)+list(weights)):
        raise ValueError("finite nonnegative regime inputs required")
    if any(v <= 0 for v in (*targets, *weights)) or any(min(row[-2:]) <= 0 for row in raw):
        raise ValueError("positive targets, weights and branch proxies required")
    if not math.isfinite(timeout_seconds) or timeout_seconds <= 0:
        raise ValueError("positive finite timeout required")
    deadline = time.monotonic()+timeout_seconds
    scales = [max(math.sqrt(math.fsum(row[j]**2 for row in raw)/n),1e-12) for j in range(d)]
    normalized = [[v/s for v,s in zip(row,scales)] for row in raw]
    ratios = [row[-1]/row[-2] for row in normalized]
    boundaries = [0., *sorted(set(ratios)), math.inf]
    best, certificates = None, []
    for index,(lo,hi) in enumerate(zip(boundaries,boundaries[1:])):
        if time.monotonic() > deadline:
            raise TimeoutError("bounded regime calibration deadline exceeded")
        # There are no training ratios strictly inside this interval.
        latency_active = [r <= lo for r in ratios]
        x = [row[:-2]+[row[-2] if active else 0.,0. if active else row[-1]]
             for row,active in zip(normalized,latency_active)]
        gram = [[math.fsum(w*row[i]*row[j] for row,w in zip(x,weights))
                 +(RIDGE if i==j else 0.) for j in range(d)] for i in range(d)]
        rhs = [math.fsum(w*row[j]*y for row,w,y in zip(x,weights,targets)) for j in range(d)]
        # Columns of R, normalized rays keep the linear solve well scaled.
        rays = []
        for j in range(d-2):
            ray=[0.]*d; ray[j]=1.; rays.append(ray)
        for edge in (lo,hi):
            length=math.hypot(edge,1.)
            rays.append([0.]*(d-2)+([1.,0.] if math.isinf(edge) else [edge/length,1/length]))
        gr = [[math.fsum(gram[i][j]*ray[j] for j in range(d)) for i in range(d)] for ray in rays]
        transformed = [[math.fsum(a*b for a,b in zip(ray,col)) for col in gr] for ray in rays]
        trhs = [math.fsum(a*b for a,b in zip(ray,rhs)) for ray in rays]
        zray,kkt,faces = _quadratic_fit(transformed,trhs,deadline)
        z = [math.fsum(rays[j][i]*zray[j] for j in range(d)) for i in range(d)]
        estimates = [math.fsum(v*c for v,c in zip(row[:-2],z[:-2]))
                     +max(row[-2]*z[-2],row[-1]*z[-1]) for row in normalized]
        assigned = [math.fsum(v*c for v,c in zip(row,z)) for row in x]
        mismatch = max(abs(a-b) for a,b in zip(estimates,assigned))
        if mismatch > 1e-7*max(1.,max(estimates)):
            raise ValueError("branch interval feasibility failed")
        objective = math.fsum(w*(p-y)**2 for w,p,y in zip(weights,estimates,targets))
        objective += RIDGE*math.fsum(c*c for c in z)
        certificate = {"interval":index,"normalized_ratio_lower":lo,
            "normalized_ratio_upper":None if math.isinf(hi) else hi,
            "objective_us2":objective,"kkt_relative_violation":kkt,
            "visited_faces":faces,"branch_feasibility_error_us":mismatch}
        certificates.append(certificate)
        if best is None or objective < best[0]:
            best=(objective,index,z,x)
    objective,index,z,x=best
    coefficients=[c/s for c,s in zip(z,scales)]
    branch_counts=Counter("latency" if row[-2]*z[-2] > row[-1]*z[-1]+1e-7 else
                         "throughput" if row[-1]*z[-1] > row[-2]*z[-2]+1e-7 else "tie"
                         for row in normalized)
    return {"coefficients_us":coefficients,"training_scales":scales,
        "objective_us2":objective,"feature_count":d,"ridge":RIDGE,
        "unregularized_rank":matrix_rank(x),
        "kkt_relative_violation":max(c["kkt_relative_violation"] for c in certificates),
        "selected_interval":index,"interval_count":len(certificates),
        "interval_certificates":certificates,"training_branch_counts":dict(branch_counts),
        "crossover_W_over_L":coefficients[-2]/coefficients[-1] if coefficients[-1]>0 else None,
        "crossover_note":"Null means zero throughput coefficient; no finite crossover. A finite ratio alone does not establish branch identification.",
        "optimality_scope":"All training-ratio cones enumerated, each numerically KKT-certified, fixed basis/weights/ridge only; no physical identification.",
        "max_faces_per_interval":1 << d}


@dataclass(frozen=True)
class RegimeModel:
    variant: str
    baseline: MechanismModel
    fused: dict

    @property
    def context_id(self):
        return self.baseline.context_id

    @property
    def training_shapes(self):
        return self.baseline.training_shapes

    @property
    def training_config_ids(self):
        return self.baseline.training_config_ids

    @classmethod
    def fit(cls,configs,*,variant="regime_max",include_flagged=False):
        if variant not in VARIANTS:
            raise ValueError("unknown regime variant")
        # Reuse the exact evidence/identity validation and unchanged host fits.
        baseline=MechanismModel.fit(configs,variant="cutlass_depth",include_flagged=include_flagged)
        rows=sorted((r for r in configs if r["family"] not in HOSTS),key=lambda r:r["config_id"])
        if "fused" not in baseline.models:
            raise ValueError("need at least two fused training shapes")
        vectors=[regime_basis(r["shape"],r["family"])[1] for r in rows]
        counts=Counter(tuple(r["shape"]) for r in rows)
        weights=[1/counts[tuple(r["shape"])] for r in rows]
        solver=max_branch_fit if variant=="regime_max" else nonnegative_fit
        fitted=solver(vectors,[r["observed_us"] for r in rows],weights)
        fused={**baseline.models["fused"],**fitted,"names":NAMES,
            "feature_bounds":[[min(v[j] for v in vectors),max(v[j] for v in vectors)] for j in range(len(NAMES))]}
        fused.pop("enumerated_faces",None) if variant=="regime_max" else None
        return cls(variant,baseline,fused)

    def predict(self,shape,family,*,context_id,dependency_policy=None):
        result=self.baseline.predict(shape,family,context_id=context_id,dependency_policy=dependency_policy)
        if family in HOSTS:
            return result
        names,values=regime_basis(shape,family)
        potential={n:v*c for n,v,c in zip(names,values,self.fused["coefficients_us"])}
        terms=dict(potential)
        l,w=potential[names[-2]],potential[names[-1]]
        if self.variant=="regime_max":
            # Exact ties use latency once; never double count the shared maximum.
            terms[names[-1] if l>=w else names[-2]]=0.
        estimate=math.fsum(terms.values())
        if not math.isfinite(estimate) or estimate<=0:
            raise ValueError("invalid regime prediction")
        result.update(predicted_us=estimate,contributions_us=terms,
            feature_extrapolation=[n for n,v,(lo,hi) in zip(names,values,self.fused["feature_bounds"])
                                   if v<lo-1e-12 or v>hi+1e-12],
            coefficient_identification="rank_deficient" if self.fused["unregularized_rank"]<len(names)
                else "full_column_rank_not_causal_identification",
            regime={"composition":"max" if self.variant=="regime_max" else "sum",
                "latency_proxy_us":l,"throughput_proxy_us":w,
                "dominant_proxy":"tie" if abs(l-w)<=1e-7 else "latency" if l>w else "throughput",
                "branch_margin_us":abs(l-w),"W_over_L":values[-1]/values[-2],
                "physical_bottleneck_identified":False})
        return result

    def to_dict(self):
        result=self.baseline.to_dict()
        result.update(schema="edmir.regime-prediction.v1",variant=self.variant,
                      models={**result["models"],"fused":self.fused})
        return result
